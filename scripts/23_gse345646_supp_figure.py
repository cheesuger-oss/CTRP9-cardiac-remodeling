#!/usr/bin/env python3
"""Build the preregistered GSE345646 single-nucleus validation figure.

Source data are the reviewed cluster annotations and donor-level C1QTNF9
pseudobulk tables generated by scripts 20--22. Donors, not nuclei, are the
replicate unit for panels c--e.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import anndata as ad
import matplotlib.pyplot as plt
import matplotlib.patheffects as pe
import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "analysis/external_validation/GSE345646"
RESULTS = BASE / "results"
FIGURES = ROOT / "figures"

def setup_style(**_kwargs):
    """Apply the portable style used by the archived figure."""
    plt.style.use("default")
    plt.rcParams.update({"font.family": "Arial", "svg.fonttype": "none", "pdf.fonttype": 42})


def add_panel_labels(fig, axes, labels, fontsize=8, **_kwargs):
    for axis, panel in zip(axes, labels):
        axis.text(-0.08, 1.02, panel, transform=axis.transAxes, fontsize=fontsize,
                  fontweight="bold", ha="right", va="bottom")


def export_figure(fig, stem, formats, dpi=600, **_kwargs):
    for suffix in formats:
        fig.savefig(f"{stem}.{suffix}", dpi=dpi, facecolor="white")


CELL_COLORS = {
    "Adipocyte": "#CC79A7",
    "Cardiomyocyte": "#D55E00",
    "Endothelial": "#0072B2",
    "Fibroblast": "#009E73",
    "Lymphatic_endothelial": "#56B4E9",
    "Macrophage_myeloid": "#E69F00",
    "Neural_Schwann": "#AA4499",
    "Pericyte": "#999933",
    "Smooth_muscle": "#332288",
    "T_cell": "#882255",
}

DISPLAY = {
    "Lymphatic_endothelial": "Lymphatic endothelial",
    "Macrophage_myeloid": "Macrophage/myeloid",
    "Neural_Schwann": "Neural/Schwann",
    "Smooth_muscle": "Smooth muscle",
    "T_cell": "T cell",
}

GROUPS = ["NF", "pRV", "RVF"]
GROUP_COLORS = {"NF": "#777777", "pRV": "#0072B2", "RVF": "#D55E00"}


def label(name: str) -> str:
    return DISPLAY.get(name, name)


def load_inputs():
    ann = pd.read_csv(BASE / "cluster_annotation_v1.tsv", sep="\t", dtype=str)
    loc = pd.read_csv(RESULTS / "C1QTNF9_celltype_localization.tsv", sep="\t")
    donor = pd.read_csv(RESULTS / "C1QTNF9_pseudobulk_by_donor_celltype.tsv", sep="\t")
    tests = pd.read_csv(RESULTS / "C1QTNF9_stage_tests.tsv", sep="\t")
    obj = ad.read_h5ad(RESULTS / "GSE345646_clustered_hvg.h5ad", backed="r")
    coords = np.asarray(obj.obsm["X_umap"])
    clusters = obj.obs["leiden_0.5"].astype(str).to_numpy()
    obj.file.close()
    mapping = dict(zip(ann["cluster"], ann["cell_type"]))
    cell_types = np.array([mapping[x] for x in clusters])
    return coords, cell_types, loc, donor, tests


def build_figure():
    setup_style(journal="nature", lang="en", constrained_layout=True)
    plt.rcParams.update({
        "font.size": 6.5,
        "axes.titlesize": 7.2,
        "axes.labelsize": 6.8,
        "xtick.labelsize": 6.0,
        "ytick.labelsize": 6.0,
        "legend.fontsize": 6.0,
        "axes.linewidth": 0.6,
    })
    coords, cell_types, loc, donor, tests = load_inputs()

    fig = plt.figure(figsize=(7.205, 4.72), layout="constrained")
    outer = fig.add_gridspec(2, 2, width_ratios=(1.03, 1.25), height_ratios=(1.0, 0.92))
    ax_a = fig.add_subplot(outer[:, 0])
    ax_b = fig.add_subplot(outer[0, 1])
    bottom = outer[1, 1].subgridspec(1, 3, wspace=0.12)
    ax_c = fig.add_subplot(bottom[0, 0])
    ax_d = fig.add_subplot(bottom[0, 1], sharey=ax_c)
    ax_e = fig.add_subplot(bottom[0, 2], sharey=ax_c)

    # a, cell-class map. Points are rasterized while all labels remain editable.
    rng = np.random.default_rng(20261115)
    order = rng.permutation(len(coords))
    for ct in CELL_COLORS:
        mask = cell_types[order] == ct
        xy = coords[order][mask]
        ax_a.scatter(xy[:, 0], xy[:, 1], s=0.45, c=CELL_COLORS[ct], alpha=0.42,
                     linewidths=0, rasterized=True)
    for ct in CELL_COLORS:
        xy = coords[cell_types == ct]
        center = np.median(xy, axis=0)
        ax_a.text(center[0], center[1], label(ct), ha="center", va="center",
                  fontsize=5.5, weight="bold", color=CELL_COLORS[ct],
                  path_effects=[pe.withStroke(linewidth=1.8, foreground="white")])
    ax_a.set_title("Reviewed major cell classes", loc="left", pad=4)
    ax_a.set_xlabel("UMAP 1")
    ax_a.set_ylabel("UMAP 2")
    ax_a.set_xticks([])
    ax_a.set_yticks([])
    for spine in ax_a.spines.values():
        spine.set_visible(False)

    # b, transcript localization. CPM is the position; positive fraction is dot area.
    loc = loc.sort_values("C1QTNF9_CPM", ascending=True).reset_index(drop=True)
    y = np.arange(len(loc))
    sizes = 18 + 2350 * loc["C1QTNF9_positive_fraction"].to_numpy()
    colors = [CELL_COLORS[x] for x in loc["cell_type"]]
    ax_b.hlines(y, 0, loc["C1QTNF9_CPM"], color="#D9D9D9", linewidth=0.8, zorder=1)
    ax_b.scatter(loc["C1QTNF9_CPM"], y, s=sizes, c=colors, edgecolor="white",
                 linewidth=0.45, zorder=2)
    for i, row in loc.iterrows():
        ax_b.text(row["C1QTNF9_CPM"] + 0.07, i,
                  f'{int(row["donors_nonzero"])}/11', va="center", fontsize=5.5)
    ax_b.set_yticks(y, [label(x) for x in loc["cell_type"]])
    ax_b.set_xlim(0, max(3.0, loc["C1QTNF9_CPM"].max() + 0.65))
    ax_b.set_xlabel(r"$C1QTNF9$ expression (CPM)")
    ax_b.set_title("Cell-type localization", loc="left", pad=4)
    ax_b.text(0.99, 0.02, "Dot area: positive-nucleus fraction\nText: donors with ≥1 count",
              transform=ax_b.transAxes, ha="right", va="bottom", fontsize=5.5,
              color="#555555")
    ax_b.spines[["top", "right", "left"]].set_visible(False)
    ax_b.tick_params(axis="y", length=0)
    ax_b.grid(axis="x", color="#EEEEEE", linewidth=0.5, zorder=0)

    # c--e, donor-level pseudobulk; deterministic jitter and median only.
    candidates = ["Endothelial", "Cardiomyocyte", "Macrophage_myeloid"]
    axes = [ax_c, ax_d, ax_e]
    jitter = np.array([-0.10, -0.035, 0.035, 0.10])
    for ax, ct in zip(axes, candidates):
        sub = donor[donor["cell_type"] == ct].copy()
        result = tests[tests["cell_type"] == ct].iloc[0]
        for xi, group in enumerate(GROUPS):
            vals = sub.loc[sub["group"] == group, "C1QTNF9_log2_CPM_plus_0.5"].to_numpy()
            ax.scatter(xi + jitter[:len(vals)], vals, s=21, c=GROUP_COLORS[group],
                       edgecolor="white", linewidth=0.45, zorder=3)
            median = np.median(vals)
            ax.plot([xi - 0.20, xi + 0.20], [median, median], color="black",
                    linewidth=1.2, solid_capstyle="round", zorder=4)
        ax.set_xticks(range(3), GROUPS)
        ax.set_xlim(-0.42, 2.42)
        ax.set_title(label(ct), pad=4)
        ax.text(0.03, 0.97,
                f'KW FDR={result["kruskal_BH_FDR"]:.3f}\nTrend FDR={result["spearman_BH_FDR"]:.3f}',
                transform=ax.transAxes, ha="left", va="top", fontsize=5.5,
                color="#333333")
        ax.axhline(-1, color="#DDDDDD", linewidth=0.55, zorder=0)
        ax.spines[["top", "right"]].set_visible(False)
        ax.tick_params(axis="x", length=0, pad=2)
    ax_c.set_ylabel(r"Donor pseudobulk $\log_2$(CPM + 0.5)")
    ax_d.tick_params(labelleft=False)
    ax_e.tick_params(labelleft=False)
    ax_c.text(0.0, -0.26, "n = 4     4     3", transform=ax_c.transAxes, fontsize=5.5)
    ax_d.text(0.0, -0.26, "n = 4     4     3", transform=ax_d.transAxes, fontsize=5.5)
    ax_e.text(0.0, -0.26, "n = 4     4     3", transform=ax_e.transAxes, fontsize=5.5)

    add_panel_labels(fig, axes=[ax_a, ax_b, ax_c, ax_d, ax_e],
                     labels=list("abcde"), style="nature", fontsize=8,
                     x_offset_pt=-8, y_offset_pt=1, ha="right")
    return fig


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--preview", action="store_true")
    parser.add_argument("--export", action="store_true")
    args = parser.parse_args()
    if not (args.preview or args.export):
        parser.error("choose --preview and/or --export")
    fig = build_figure()
    FIGURES.mkdir(exist_ok=True)
    if args.preview:
        preview = FIGURES / "SuppFig_GSE345646_single_nucleus_preview.png"
        fig.savefig(preview, dpi=180, bbox_inches=None, facecolor="white")
        print(preview)
    if args.export:
        export_figure(
            fig,
            str(FIGURES / "SuppFig_GSE345646_single_nucleus"),
            formats=["svg", "pdf", "tiff", "png"],
            size_inches=(7.205, 4.72),
            dpi=600,
            grayscale_preview=True,
            tight=False,
        )
    plt.close(fig)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
